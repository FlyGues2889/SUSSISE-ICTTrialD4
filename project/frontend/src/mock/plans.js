const CONTRA = {
  neck: '颈椎病急性期、肩袖损伤禁做颈部环绕；放射性疼痛禁做',
  back: '腰椎间盘突出急性期禁做前屈；下肢放射痛禁做',
  full: '急性疼痛期、术后未满3个月禁做',
}

const AREA_LABELS = { neck: '肩颈', back: '腰背', full: '全身' }
const SCENE_LABELS = { desk: '办公桌前', standing: '站立休息', home: '居家' }

export function generatePlans() {
  const plans = []
  let id = 1
  for (const area of ['neck', 'back', 'full']) {
    for (const dur of [3, 5, 10, 15]) {
      for (const scene of ['desk', 'standing', 'home']) {
        const movements = TEMPLATES[`${area}-${dur}`]
        if (!movements) continue
        plans.push({
          plan_id: id++,
          name: `${SCENE_LABELS[scene]}${dur}分钟${AREA_LABELS[area]}运动`,
          duration_min: dur,
          target_area: area,
          scene,
          movements,
          suitable_level: area === 'full' ? 'low,medium,high' : 'low,medium',
          contraindication: CONTRA[area],
          description: `针对${AREA_LABELS[area]}的${dur}分钟碎片化运动方案，适合${SCENE_LABELS[scene]}场景`,
          evidence: healthEvidence.getPlanEvidence(area),
        })
      }
    }
  }
  return plans
}